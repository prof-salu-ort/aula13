'''
Considere a lista numeros = [10, 20, 30, 40, 50, 60, 70, 80]. 
Escreva as expressões de fatiamento ([inicio:fim]) para extrair:
- Os três primeiros elementos ([10, 20, 30]).
- Os elementos do índice 4 até o final da lista.
- Uma sub-lista contendo apenas [40, 50, 60].

'''

numeros = [10, 20, 30, 40, 50, 60, 70, 80]

print(numeros)
print('Tres primeiros elementos:', numeros[0:3])
print('Indice 4 até o final:', numeros[4:])
print('Valores 40, 50 e 60:', numeros[3:7])
